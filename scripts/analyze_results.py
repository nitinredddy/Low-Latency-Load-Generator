#!/usr/bin/env python3
"""
Performance Analysis & Visualization Tool for Low-Latency Load Generator
Processes benchmark CSV outputs and generates latency CDFs, time-series, and Coordinated Omission charts.
"""

import argparse
import sys
import os

def parse_args():
    parser = argparse.ArgumentParser(description="Analyze and plot low-latency load generator benchmark results.")
    parser.add_argument("csv_file", help="Path to CSV timeseries generated by load_generator (--output)")
    parser.add_argument("--plot", help="Path to save output visualization (e.g. latency_dashboard.png)")
    parser.add_argument("--title", default="Low-Latency Load Generator Benchmark", help="Plot title")
    return parser.parse_args()

def analyze_and_plot():
    args = parse_args()

    if not os.path.exists(args.csv_file):
        print(f"Error: File '{args.csv_file}' not found.", file=sys.stderr)
        sys.exit(1)

    import numpy as np

    try:
        data = np.genfromtxt(args.csv_file, delimiter=',', names=True)
    except Exception as e:
        print(f"Error reading CSV: {e}", file=sys.stderr)
        sys.exit(1)

    if data.size == 0 or 'service_time_us' not in data.dtype.names:
        print("Error: CSV does not contain valid latency columns.", file=sys.stderr)
        sys.exit(1)

    service_lat = data['service_time_us']
    total_lat = data['total_latency_us']
    schedule_delay = data['schedule_delay_us']

    count = len(service_lat)
    p50 = np.percentile(service_lat, 50)
    p90 = np.percentile(service_lat, 90)
    p95 = np.percentile(service_lat, 95)
    p99 = np.percentile(service_lat, 99)
    p999 = np.percentile(service_lat, 99.9)
    max_lat = np.max(service_lat)
    mean_lat = np.mean(service_lat)
    std_lat = np.std(service_lat)

    print("\n" + "=" * 60)
    print("         DETAILED LATENCY ANALYSIS REPORT")
    print("=" * 60)
    print(f" Total Samples:         {count:,}")
    print(f" Mean Latency:          {mean_lat:.2f} µs ({mean_lat/1000.0:.3f} ms)")
    print(f" Std Dev:               {std_lat:.2f} µs")
    print(f" Min Latency:           {np.min(service_lat):.2f} µs")
    print(f" Median (p50):          {p50:.2f} µs")
    print(f" 90th Percentile (p90): {p90:.2f} µs")
    print(f" 95th Percentile (p95): {p95:.2f} µs")
    print(f" 99th Percentile (p99): {p99:.2f} µs")
    print(f" 99.9th Percentile:     {p999:.2f} µs")
    print(f" Maximum Latency:       {max_lat:.2f} µs ({max_lat/1000.0:.3f} ms)")
    print("-" * 60)
    print(f" Mean Schedule Delay:   {np.mean(schedule_delay):.2f} µs")
    print(f" Max Schedule Delay:    {np.max(schedule_delay):.2f} µs")
    print(f" Corrected p99 Latency: {np.percentile(total_lat, 99):.2f} µs")
    print("=" * 60 + "\n")

    if args.plot:
        try:
            import matplotlib
            matplotlib.use('Agg')
            import matplotlib.pyplot as plt
        except ImportError:
            print("matplotlib is not installed. Run 'pip install matplotlib' to enable plotting.")
            return

        plt.style.use('seaborn-v0_8-whitegrid' if 'seaborn-v0_8-whitegrid' in plt.style.available else 'default')
        fig, axs = plt.subplots(2, 2, figsize=(14, 10))
        fig.suptitle(args.title, fontsize=16, fontweight='bold')

        # 1. Latency CDF
        sorted_service = np.sort(service_lat)
        sorted_total = np.sort(total_lat)
        yvals = np.arange(len(sorted_service)) / float(len(sorted_service) - 1) * 100.0

        axs[0, 0].plot(sorted_service, yvals, label="Service Time (Raw)", color="#1f77b4", lw=2)
        axs[0, 0].plot(sorted_total, yvals, label="Corrected (CO Aware)", color="#d62728", lw=2, linestyle="--")
        axs[0, 0].set_title("Latency Cumulative Distribution Function (CDF)")
        axs[0, 0].set_xlabel("Latency (µs)")
        axs[0, 0].set_ylabel("Percentile (%)")
        axs[0, 0].axvline(p99, color="#1f77b4", linestyle=":", label=f"Raw p99: {p99:.1f}µs")
        axs[0, 0].legend()
        axs[0, 0].grid(True, alpha=0.3)

        # 2. Timeline Scatter (Microbursts)
        subsample = min(count, 5000)
        idx_step = max(1, count // subsample)
        axs[0, 1].scatter(data['seq'][::idx_step], service_lat[::idx_step], alpha=0.5, s=8, color="#2ca02c")
        axs[0, 1].set_title("Request Latency Over Time (Microburst Detection)")
        axs[0, 1].set_xlabel("Request Sequence ID")
        axs[0, 1].set_ylabel("Service Latency (µs)")
        axs[0, 1].axhline(p99, color="#d62728", linestyle="--", label=f"p99 ({p99:.1f}µs)")
        axs[0, 1].legend()
        axs[0, 1].grid(True, alpha=0.3)

        # 3. High-Percentile Log Curve
        percentiles = [0, 50, 75, 90, 95, 99, 99.5, 99.9, 99.99]
        valid_p = [p for p in percentiles if p < 100.0 * (1.0 - 1.0/count)]
        if valid_p:
            p_vals_serv = [np.percentile(service_lat, p) for p in valid_p]
            p_vals_tot = [np.percentile(total_lat, p) for p in valid_p]
            labels = [f"p{p}" for p in valid_p]
            axs[1, 0].plot(labels, p_vals_serv, marker='o', label="Service Time", color="#1f77b4")
            axs[1, 0].plot(labels, p_vals_tot, marker='s', label="Corrected Latency", color="#d62728")
            axs[1, 0].set_title("Tail Latency Progression (p50 to p99.99)")
            axs[1, 0].set_xlabel("Percentile Tier")
            axs[1, 0].set_ylabel("Latency (µs)")
            axs[1, 0].set_yscale('log')
            axs[1, 0].legend()
            axs[1, 0].grid(True, alpha=0.3)

        # 4. Schedule Delay Distribution
        axs[1, 1].hist(schedule_delay, bins=50, color="#9467bd", edgecolor='black', alpha=0.7)
        axs[1, 1].set_title("Schedule Jitter / Queue Delay Distribution")
        axs[1, 1].set_xlabel("Schedule Delay (µs)")
        axs[1, 1].set_ylabel("Frequency")
        axs[1, 1].grid(True, alpha=0.3)

        plt.tight_layout()
        plt.savefig(args.plot, dpi=300)
        print(f"[+] Visualization dashboard successfully saved to: {args.plot}")

if __name__ == "__main__":
    analyze_and_plot()
